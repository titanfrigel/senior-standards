// Finds AI attribution in commit and PR text: co-author trailers, "generated
// with" footers and model identifiers. Bare product mentions ("OpenCode
// adapter", "support Claude Code hooks") are deliberately not flagged.

const MAX_SNIPPET = 80;
const MAX_TEXT = 64 * 1024;
const MAX_MATCHES = 20;

// Names that rarely belong to anything but an AI tool or vendor.
const DISTINCT_NAMES = [
  "anthropic",
  "opencode",
  "openai",
  "chatgpt",
  "gpt",
  "copilot",
  "gemini",
  "codex",
  "windsurf",
  "codeium",
  "tabnine",
  "amazon q",
  "codewhisperer",
  "llama",
  "mistral",
  "qwen",
  "deepseek",
];
// Also personal names or common words; trusted only with more context.
const AMBIGUOUS_NAMES = ["claude", "devin", "cursor", "grok"];

const alternation = (names) => names.join("|");
// Not `\b`: the name may follow markup such as `_` or `*`.
const NAME = `(?<![A-Za-z0-9])(?:${alternation([...DISTINCT_NAMES, ...AMBIGUOUS_NAMES])})(?![-A-Za-z0-9])`;
const DISTINCT = new RegExp(
  String.raw`\b(?:${alternation(DISTINCT_NAMES)})\b`,
  "i",
);
const AMBIGUOUS = new RegExp(
  String.raw`\b(?:${alternation(AMBIGUOUS_NAMES)})\b`,
  "i",
);
// An ambiguous name followed by a product or model word, e.g. "Claude Opus 5.5".
const PRODUCT =
  /\b(?:claude[ \t]+(?:opus|sonnet|haiku|fable|instant|code|\d)|claude-(?:opus|sonnet|haiku|fable|instant)|cursor[ \t]+agent|devin[ \t]+ai)\b/i;
const VENDOR_DOMAIN =
  /@(?:[\w-]+\.)*(?:anthropic\.com|openai\.com|cursor\.com|cursor\.sh|cognition\.ai|cognition-labs\.com|x\.ai|githubcopilot\.com)\b/i;
const BOT_ADDRESS = /\[bot\]@users\.noreply\.github\.com/i;
const NOREPLY = /^(?:no-?reply|bot|ai|assistant)$/i;
const GITHUB_NOREPLY =
  /^(?:\d+\+)?([^@]+?)(?:\[bot\])?@users\.noreply\.github\.com$/i;

/** A vendor address, or a GitHub noreply address whose handle names an AI tool. */
function isAiAddress(email) {
  if (VENDOR_DOMAIN.test(email)) return true;
  const handle = GITHUB_NOREPLY.exec(email.trim())?.[1];
  return (
    handle !== undefined && (DISTINCT.test(handle) || AMBIGUOUS.test(handle))
  );
}

/** True when a `Co-Authored-By` value (name and optional email) names an AI tool. */
function isAiCoAuthor(name, email) {
  if (VENDOR_DOMAIN.test(email) || DISTINCT.test(name) || PRODUCT.test(name)) {
    return true;
  }
  if (
    BOT_ADDRESS.test(email) &&
    (DISTINCT.test(email) || AMBIGUOUS.test(email))
  ) {
    return true;
  }
  // A lone ambiguous word ("Claude <noreply@…>") with no personal-looking address.
  const [local = ""] = email.split("@");
  return (
    AMBIGUOUS.test(name) &&
    name.trim().split(/\s+/).length === 1 &&
    (email === "" || NOREPLY.test(local) || isAiAddress(email))
  );
}

const PHRASE = [
  String.raw`with\s+(?:the\s+)?(?:help|assistance)\s+(?:of|from)`,
  String.raw`(?:generated|created|written)\s+(?:with|by|using)`,
  String.raw`assisted\s+by`,
  String.raw`co-written\s+(?:with|by)`,
  String.raw`built\s+with`,
  String.raw`made\s+with`,
].join("|");
const VENDOR_PREFIX = String.raw`(?:(?:github|microsoft|google|amazon|anthropic|openai)\s+)?`;
// Up to four short filler words or punctuation marks between phrase and name.
const FILLER = String.raw`(?:(?:the|help|of|assistance|from|an|a|ai|model|assistant|tool|using|via|by)(?![A-Za-z0-9])\s*|[:(]\s*){0,4}`;
const OPENING_MARKUP = String.raw`[\[\x60*_]*`;
// Closing markup of a name or markdown link, with up to three words of the name.
const CLOSING_MARKUP = String.raw`(?:(?:[ \t]+[\w.]+){0,3}[\]\x60*_)]+(?:\([^)\r\n]*\))?)?`;
// The name must follow the phrase directly: "created by the OpenCode adapter"
// and "generated by pnpm, no longer breaks OpenCode" are ordinary wording.
const FOOTER = new RegExp(
  String.raw`\b(?:${PHRASE})\s+${FILLER}${OPENING_MARKUP}${VENDOR_PREFIX}${NAME}(?!\s+(?:adapter|plugin|hook|integration)\b)${CLOSING_MARKUP}`,
  "gi",
);

const MODEL_ID = new RegExp(
  [
    String.raw`\bclaude-(?:opus|sonnet|haiku|fable|instant)[-\w.]*`,
    String.raw`\bclaude \d`,
    String.raw`\bgpt-\d[\w.-]*`,
    String.raw`\bmodel[ \t]*[:=]?[ \t]*o\d(?:-mini|-pro)?\b`,
    String.raw`\bgemini-\d[\w.-]*`,
    String.raw`\bllama-?\d`,
    String.raw`\bqwen\d`,
    String.raw`\bdeepseek-[vr]\d`,
  ].join("|"),
  "gi",
);

// Ordered by priority: a later match inside an earlier one is dropped.
const PATTERNS = [
  {
    pattern: /co-authored-by:[ \t]*([^\r\n<"']*)(?:<([^>\r\n]*)>)?/gi,
    accept: (match) => isAiCoAuthor(match[1], match[2] ?? ""),
  },
  { pattern: /🤖[ \t]*generated[^\r\n]*/gi },
  { pattern: FOOTER },
  { pattern: MODEL_ID },
];

function snippetOf(text) {
  return text
    .trim()
    .replace(/[.-]+$/, "")
    .slice(0, MAX_SNIPPET)
    .trim();
}

/**
 * Distinct snippets of AI attribution found in the first 64 KB of `text`
 * (at most 20); [] when there is none.
 */
export function findAttribution(text) {
  const scanned = text.slice(0, MAX_TEXT);
  const taken = [];
  const found = new Set();
  for (const { pattern, accept } of PATTERNS) {
    for (const match of scanned.matchAll(pattern)) {
      if (found.size >= MAX_MATCHES) return [...found];
      if (accept && !accept(match)) continue;
      const start = match.index;
      const end = start + match[0].length;
      if (taken.some(([s, e]) => start < e && end > s)) continue;
      taken.push([start, end]);
      found.add(snippetOf(match[0]));
    }
  }
  return [...found];
}
