// Copies the CI dependency check and the core files it imports into
// <projectDir>/.github/scripts/senior-standards/, keeping the core/ layout,
// so a project's CI can run it with Node alone.
//
// Usage: node scripts/vendor-dependency-check.mjs <projectDir>

import {
  copyFile,
  mkdir,
  readdir,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const CORE_FILES = [
  "dependency-check.mjs",
  "approval.mjs",
  "adr-index.mjs",
  "diff-manifest.mjs",
];
const TARGET = [".github", "scripts", "senior-standards"];

function readme(version) {
  return `# senior-standards dependency check

Generated by senior-standards ${version}. Do not edit these files: they are
copied verbatim from the plugin's \`core/\` folder and are overwritten on refresh.

CI runs:

    node .github/scripts/senior-standards/core/dependency-check.mjs --base <base commit SHA>

It fails when a change adds a direct dependency that no accepted ADR in
\`docs/adr\` lists in \`packages\`. Check out with \`fetch-depth: 0\` so the base
commit is available.

To refresh, run \`node <plugin>/scripts/vendor-dependency-check.mjs <project>\`
from an installed senior-standards plugin (or ask the repo-standards skill).
\`VERSION\` names the plugin version these files came from.
`;
}

async function vendor(projectDir) {
  const { version } = JSON.parse(
    await readFile(path.join(repoRoot, "package.json"), "utf8"),
  );
  const target = path.join(projectDir, ...TARGET);
  // The folder is generated: clear it so removed files do not linger.
  await rm(target, { recursive: true, force: true });
  await mkdir(path.join(target, "core", "manifests"), { recursive: true });

  const coreDir = path.join(repoRoot, "core");
  for (const name of CORE_FILES) {
    await copyFile(path.join(coreDir, name), path.join(target, "core", name));
  }
  const manifestsDir = path.join(coreDir, "manifests");
  const manifests = (await readdir(manifestsDir)).filter((name) =>
    name.endsWith(".mjs"),
  );
  for (const name of manifests) {
    await copyFile(
      path.join(manifestsDir, name),
      path.join(target, "core", "manifests", name),
    );
  }
  await writeFile(path.join(target, "VERSION"), `${version}\n`);
  await writeFile(path.join(target, "README.md"), readme(version));
  return target;
}

async function main() {
  const projectArg = process.argv[2];
  if (!projectArg) {
    process.stderr.write(
      "Usage: node scripts/vendor-dependency-check.mjs <projectDir>\n",
    );
    process.exitCode = 2;
    return;
  }
  const target = await vendor(path.resolve(projectArg));
  process.stdout.write(`vendor-dependency-check: wrote ${target}\n`);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await main();
}
