import assert from "node:assert/strict";
import { test } from "node:test";
import { findAttribution } from "../../core/attribution.mjs";

const flagged = (text) => findAttribution(text).length > 0;

test("Co-Authored-By naming an AI assistant, vendor or model is flagged", () => {
  for (const line of [
    "Co-Authored-By: Claude <noreply@anthropic.com>",
    "co-authored-by: ChatGPT <bot@example.com>",
    "CO-AUTHORED-BY: GitHub Copilot <copilot@github.com>",
    "Co-authored-by: Bot <noreply@openai.com>",
    "Co-Authored-By: Gemini <g@example.com>",
    "Co-Authored-By: Amazon Q Developer <q@example.com>",
    "Co-Authored-By: opencode <o@example.com>",
    "Co-Authored-By: DeepSeek <d@example.com>",
  ]) {
    assert.ok(flagged(`feat: x\n\n${line}\n`), line);
  }
});

test("Co-Authored-By naming a human is not flagged", () => {
  assert.deepEqual(
    findAttribution("Co-Authored-By: Ada Lovelace <ada@example.com>"),
    [],
  );
});

test("attribution footers and phrases followed by a tool name are flagged", () => {
  for (const text of [
    "Generated with Claude Code",
    "generated by ChatGPT",
    "Created using Copilot",
    "written with Cursor",
    "Assisted by Claude",
    "co-written by Gemini",
    "Built with OpenCode",
    "made with Codex",
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "🤖 Generated by something",
  ]) {
    assert.ok(flagged(text), text);
  }
});

test("a footer phrase without a tool name on the same line is not flagged", () => {
  assert.deepEqual(findAttribution("Generated with care\nClaude"), []);
  assert.deepEqual(findAttribution("Built with pnpm"), []);
});

test("model identifiers are flagged", () => {
  for (const text of [
    "claude-opus-4-1",
    "Claude-Sonnet-5-5",
    "claude-haiku",
    "claude 4",
    "gpt-5.1",
    "model: o3-mini",
    "model o3",
    "gemini-2.5-pro",
    "llama-3",
    "llama3",
    "qwen3",
    "deepseek-v3",
    "deepseek-r1",
  ]) {
    assert.ok(flagged(`fix: x ${text}`), text);
  }
});

test("bare product mentions are not flagged", () => {
  for (const text of [
    "fix(claude): adapter",
    "OpenCode adapter",
    "support Claude Code hooks",
    "feat(opencode): register skills",
    "the o3 key and a 100 ohm resistor",
    "docs: explain Gemini-less setup",
    "fix: files created by the OpenCode adapter are removed",
    "fix: hook output written by the Claude adapter",
    "fix: lockfile generated by pnpm no longer breaks OpenCode",
    "feat: pagination built with cursor-based API",
  ]) {
    assert.deepEqual(findAttribution(text), [], text);
  }
});

test("matches are distinct, trimmed and at most 80 characters", () => {
  const long = `Generated with Claude ${"x".repeat(200)}`;
  const text = `${long}\nCo-Authored-By: Claude <noreply@anthropic.com>\nCo-Authored-By: Claude <noreply@anthropic.com>\n`;
  const found = findAttribution(text);
  assert.equal(new Set(found).size, found.length);
  for (const snippet of found) {
    assert.ok(snippet.length <= 80);
    assert.equal(snippet, snippet.trim());
  }
  assert.equal(found.filter((s) => s.startsWith("Co-Authored-By")).length, 1);
});

test("an emoji footer line is reported once, not once per pattern", () => {
  assert.equal(
    findAttribution("🤖 Generated with [Claude Code](https://x.y)").length,
    1,
  );
});

test("CRLF text is handled", () => {
  const found = findAttribution(
    "feat: x\r\n\r\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n",
  );
  assert.deepEqual(found, ["Co-Authored-By: Claude <noreply@anthropic.com>"]);
});

test("empty and non-attribution text yields nothing", () => {
  assert.deepEqual(findAttribution(""), []);
  assert.deepEqual(findAttribution("feat: add parser\n\nbody"), []);
});

test("footers keep matching real attribution forms", () => {
  for (const text of [
    "Generated with [Claude Code](https://claude.com/claude-code)",
    "Assisted by GitHub Copilot",
    "Created with ChatGPT",
    "generated by the Claude assistant",
  ]) {
    assert.ok(flagged(text), text);
  }
});

test("Co-Authored-By with an ambiguous name needs a vendor address or a product word", () => {
  for (const line of [
    "Co-Authored-By: Claude <noreply@anthropic.com>",
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "Co-Authored-By: Claude Sonnet 4 <x@example.com>",
    "Co-Authored-By: Cursor Agent <cursoragent@cursor.com>",
    "Co-Authored-By: Devin <devin-ai-integration[bot]@users.noreply.github.com>",
    "Co-Authored-By: Grok <noreply@x.ai>",
  ]) {
    assert.ok(flagged(line), line);
  }
  for (const line of [
    "Co-Authored-By: Claude Dupont <claude.dupont@example.fr>",
    "Co-Authored-By: Devin Patel <devin@example.com>",
    "Co-Authored-By: Cursor Smith <c@example.org>",
  ]) {
    assert.deepEqual(findAttribution(line), [], line);
  }
});

test("a large input is scanned quickly and capped", () => {
  const started = Date.now();
  findAttribution("generated with ".repeat(10_000));
  findAttribution("Generated with Claude Code\n".repeat(10_000));
  assert.ok(Date.now() - started < 1000);
  const many = Array.from({ length: 100 }, (_, i) => `claude-opus-${i}`).join(
    " ",
  );
  assert.equal(findAttribution(many).length, 20);
});

test("only the first 64 KB are scanned", () => {
  assert.deepEqual(
    findAttribution(`${"x ".repeat(40_000)}Generated with Claude`),
    [],
  );
});

test("markup around the name after a footer phrase is still flagged", () => {
  for (const text of [
    "Generated with `Claude Code`",
    "Generated with *Claude Code*",
    "Generated with **Claude**",
    "Generated with _OpenCode_",
    "Generated with [`Claude Code`](https://claude.com/claude-code)",
  ]) {
    assert.ok(flagged(text), text);
  }
});

test("short filler between the phrase and the name is still flagged", () => {
  for (const text of [
    "Generated with the help of Claude",
    "Written using AI: Claude",
    "Created with assistance from ChatGPT",
    "with help from Copilot",
    "Generated using an AI model (Claude)",
  ]) {
    assert.ok(flagged(text), text);
  }
});

test("ordinary wording near a phrase still passes", () => {
  for (const text of [
    "fix: files created by the OpenCode adapter are removed",
    "fix: hook output written by the Claude adapter",
    "fix: lockfile generated by pnpm no longer breaks OpenCode",
    "feat: pagination built with cursor-based API",
    "docs: made with the help of a style guide for Claude users",
    "fix: generated by the build, see the Claude Code docs",
  ]) {
    assert.deepEqual(findAttribution(text), [], text);
  }
});

test("filler matching stays linear on adversarial input", () => {
  const started = Date.now();
  findAttribution(`generated with ${"the ".repeat(15_000)}`);
  findAttribution(`generated with ${"a ( ".repeat(15_000)}x`);
  assert.ok(Date.now() - started < 1000);
});

test("GitHub noreply addresses of AI tools are flagged, humans are not", () => {
  for (const line of [
    "Co-Authored-By: Cursor <cursor@users.noreply.github.com>",
    "Co-Authored-By: Claude <claude@users.noreply.github.com>",
    "Co-Authored-By: Devin AI <devin-ai-integration@users.noreply.github.com>",
    "Co-Authored-By: Claude <12345+claude@users.noreply.github.com>",
    "Co-Authored-By: Claude <noreply@example.com>",
  ]) {
    assert.ok(flagged(line), line);
  }
  for (const line of [
    "Co-Authored-By: Jane Doe <12345+janedoe@users.noreply.github.com>",
    "Co-Authored-By: Claude Dupont <claude.dupont@example.fr>",
  ]) {
    assert.deepEqual(findAttribution(line), [], line);
  }
});

test("snippets keep the closing of a markdown name or link", () => {
  assert.deepEqual(
    findAttribution("Generated with [Claude Code](https://x.y/z)"),
    ["Generated with [Claude Code](https://x.y/z)"],
  );
  assert.deepEqual(findAttribution("Generated with **Claude**"), [
    "Generated with **Claude**",
  ]);
  assert.deepEqual(findAttribution("Generated with Claude Code"), [
    "Generated with Claude",
  ]);
  const long = `Generated with [Claude Code](https://x.y/${"z".repeat(100)})`;
  assert.ok(findAttribution(long)[0].length <= 80);
});
